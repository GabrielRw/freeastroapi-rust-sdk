#!/usr/bin/env python3
"""Generate the Rust SDK's types, resources and operation tests from the vendored OpenAPI document.

    python3 scripts/generate.py           write src/generated/*.rs, tests/operations.rs, tests/contract.rs
    python3 scripts/generate.py --check   fail if they are out of date
    python3 scripts/generate.py --spec SPEC --out-dir DIR --tests-file FILE --contract-file FILE
                                          generate from another spec (used by the fixture test)

Dependency-free (Python 3.9+ standard library only). Output is deterministic: the same spec always
produces byte-identical files, so CI can diff them.

OpenAPI 3.1 handling (no preprocessing of the vendored file is needed; everything happens here):
  * `type: [T, "null"]`, `anyOf: [T, {type: null}]` and `enum: [.., null]` become `Option<T>`.
  * `const` string values become single-variant enums, so discriminated unions deserialise into
    the right variant even though they are emitted as `#[serde(untagged)]` enums.
  * `anyOf` members that only carry constraints (`{required: [...]}`) are ignored for typing.
  * `allOf` with one member is an alias for that member; several object members are merged.
  * Inline objects, enums and unions get named types (`<Parent><Field>`); a string enum used by a
    field name with one single set of values across the whole spec is shared under the field name.
  * String enums (and `const` values) carry a catch-all `Other(String)` variant so new server
    values never break deserialisation.
  * Response decoding is lenient: every struct reachable from a response gets `#[serde(default)]`
    and reads `null` as the field's default, so a missing "required" field, a null in a non-null
    field or an unknown field never fails. Request-only structs stay strict. Unions get a
    generated `Deserialize` that picks the variant whose required fields and `const`
    discriminators match (lenient structs would otherwise all match the first variant).
  * Response content types: JSON -> typed value (`serde_json::Value` while untyped), text-like
    (`text/*`, `image/svg+xml`, `*+xml`) -> `String`, anything else (`image/png`,
    `application/pdf`, ...) -> `Binary`, JSON plus another type -> `Content<T>`.
  * Error responses (`ErrorResponse` on 4xx/5xx) do not change method signatures; they are mapped
    to `freeastroapi::Error` at runtime.
"""

