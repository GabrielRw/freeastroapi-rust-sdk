# ---------------------------------------------------------------- naming


def split_words(text: str) -> list[str]:
    text = re.sub(r"([a-z0-9])([A-Z])", r"\1 \2", str(text))
    text = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1 \2", text)
    return [w for w in re.split(r"[^A-Za-z0-9]+", text) if w]


def snake(text: str) -> str:
    return "_".join(w.lower() for w in split_words(text))


def pascal(text: str) -> str:
    """PascalCase that keeps the casing of mixed-case words (`KPChart` stays `KPChart`)."""
    out = []
    for word in re.split(r"[^A-Za-z0-9]+", str(text)):
        if not word:
            continue
        if word.isupper() and len(word) > 1 and not any(c.isdigit() for c in word):
            word = word[0] + word[1:].lower()
        out.append(word[0].upper() + word[1:])
    return "".join(out)


def variant_name(value: str) -> str:
    words = split_words(value)
    name = "".join(w[0].upper() + w[1:].lower() for w in words)
    if not name:
        return "Empty"
    if name[0].isdigit():
        name = "V" + name
    return name


def field_ident(name: str) -> str:
    ident = snake(name) or "value"
    if ident[0].isdigit():
        ident = "n" + ident
    if ident in NON_RAW_KEYWORDS:
        return ident + "_"
    if ident in RUST_KEYWORDS:
        return "r#" + ident
    return ident


def bare(ident: str) -> str:
    return ident[2:] if ident.startswith("r#") else ident


def type_ident(name: str) -> str:
    ident = pascal(name)
    if not ident:
        ident = "Unnamed"
    if ident[0].isdigit():
        ident = "T" + ident
    if ident.isupper() and len(ident) > 1:
        ident = ident[0] + ident[1:].lower()
    return ident


def is_param(segment: str) -> bool:
    return segment.startswith("{") and segment.endswith("}")


def rust_str(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def raw_str(value: str) -> str:
    hashes = "#"
    while f'"{hashes}' in value:
        hashes += "#"
    return f'r{hashes}"{value}"{hashes}'


# ---------------------------------------------------------------- docs


LIST_RE = re.compile(r"^(?:[-*+]|\d{1,3}[.)])\s+")
URL_RE = re.compile(r"(https?://[^\s<>\]\)`'\"]+[^\s<>\]\)`'\".,;:])")


def doc_lines(*parts: Optional[str]) -> list[str]:
    """Turn spec prose into rustdoc-safe Markdown (no doctests, links or stray HTML)."""
    lines: list[str] = []
    for part in parts:
        if part is None:
            continue
        text = str(part).replace("\r\n", "\n").strip()
        if not text:
            continue
        if lines:
            lines.append("")
        for raw in text.split("\n"):
            line = raw.strip()
            if line.startswith("```") or line.startswith("~~~"):
                line = line.replace("`", "\\`").replace("~", "\\~")
            line = (
                line.replace("\\", "\\\\").replace("[", "\\[").replace("]", "\\]")
                .replace("<", "\\<").replace(">", "\\>")
            ) if not line.startswith("\\`") else line
            line = URL_RE.sub(lambda m: "<" + m.group(1).replace("\\", "") + ">", line)
            lines.append(line)
    # collapse runs of blank lines; indent list item continuations (rustdoc lazy continuation)
    out: list[str] = []
    list_indent = 0
    for line in lines:
        if line == "":
            list_indent = 0
            if not out or out[-1] == "":
                continue
            out.append(line)
            continue
        marker = LIST_RE.match(line)
        if marker:
            list_indent = len(marker.group(0))
        elif list_indent:
            line = " " * list_indent + line
        out.append(line)
    while out and out[-1] == "":
        out.pop()
    return out


def render_doc(lines: list[str], indent: str = "") -> str:
    return "".join(f"{indent}///{(' ' + line) if line else ''}\n" for line in lines)


def code_span(text: str) -> str:
    return "`" + str(text).replace("`", "'") + "`"


# ---------------------------------------------------------------- schema helpers


class Gen:
    def __init__(self, spec: dict[str, Any]):
        self.spec = spec
        self.schemas: dict[str, Any] = (spec.get("components") or {}).get("schemas") or {}
        self.names: dict[str, str] = {}  # component name -> rust ident
        self.used: set[str] = set()
        self.defs: dict[str, dict[str, Any]] = {}  # rust ident -> definition
        self.order: list[str] = []
        self.shared_enums: dict[tuple, str] = {}  # (field, signature) -> ident
        for name in self.schemas:
            ident = type_ident(name)
            if ident in RESERVED_TYPE_NAMES:
                ident += "Schema"
            if ident in self.used:
                raise SystemExit(f"schema name clash after conversion: {name} -> {ident}")
            self.used.add(ident)
            self.names[name] = ident

    # --- utilities

    def resolve(self, schema: Any) -> Any:
        seen = set()
        while isinstance(schema, dict) and "$ref" in schema:
            ref = schema["$ref"]
            if ref in seen:
                return {}
            seen.add(ref)
            schema = self.schemas.get(ref.rsplit("/", 1)[-1], {})
        return schema if isinstance(schema, dict) else {}

    def unique(self, base: str) -> str:
        name = type_ident(base)
        if name in RESERVED_TYPE_NAMES:
            name += "Type"
        candidate, n = name, 2
        while candidate in self.used:
            candidate = f"{name}{n}"
            n += 1
        self.used.add(candidate)
        return candidate

    @staticmethod
    def shape_union(schema: dict[str, Any]) -> Optional[list[Any]]:
        union = schema.get("anyOf") or schema.get("oneOf")
        if not isinstance(union, list):
            return None
        if all(isinstance(s, dict) and set(s) <= CONSTRAINT_KEYS for s in union):
            return None
        return union

    def split_null(self, schema: Any) -> tuple[Any, bool]:
        """Return the non-null part of a schema and whether null is allowed."""
        if not isinstance(schema, dict):
            return schema, False
        nullable = bool(schema.get("nullable"))
        kind = schema.get("type")
        if isinstance(kind, list) and "null" in kind:
            rest = [k for k in kind if k != "null"]
            nullable = True
            schema = {**schema, "type": rest[0] if len(rest) == 1 else rest}
            if not rest:
                return {}, True
        if isinstance(schema.get("enum"), list) and None in schema["enum"]:
            nullable = True
            schema = {**schema, "enum": [v for v in schema["enum"] if v is not None]}
        union = self.shape_union(schema)
        if union is not None:
            members = [m for m in union if not (isinstance(m, dict) and m.get("type") == "null")]
            if len(members) != len(union):
                nullable = True
                key = "anyOf" if "anyOf" in schema else "oneOf"
                base = {k: v for k, v in schema.items() if k not in ("anyOf", "oneOf")}
                if len(members) == 1 and not base.get("properties"):
                    merged = dict(members[0]) if isinstance(members[0], dict) else {}
                    for k in ("description", "default", "deprecated"):
                        if k in base and k not in merged and "$ref" not in merged:
                            merged[k] = base[k]
                    inner, _ = self.split_null(merged)
                    return inner, True
                schema = {**base, key: members}
        return schema, nullable

    def string_enum_signature(self, schema: Any) -> Optional[tuple]:
        if not isinstance(schema, dict) or "$ref" in schema:
            return None
        if "const" in schema and isinstance(schema["const"], str):
            return ("const", schema["const"])
        values = schema.get("enum")
        if isinstance(values, list) and values and all(isinstance(v, str) for v in values):
            return ("enum", tuple(values))
        return None

    # --- shared enum pre-pass

    def collect_enum_fields(self) -> None:
        usages: dict[str, set] = defaultdict(set)

        def visit_field(field: str, schema: Any) -> None:
            inner, _ = self.split_null(schema)
            if not isinstance(inner, dict):
                return
            sig = self.string_enum_signature(inner)
            if sig:
                usages[field].add(sig)
                return
            if inner.get("type") == "array" and isinstance(inner.get("items"), dict):
                visit_field(field, inner["items"])
                return
            visit_object(inner)

        def visit_object(schema: Any) -> None:
            if not isinstance(schema, dict) or "$ref" in schema:
                return
            for name, prop in (schema.get("properties") or {}).items():
                visit_field(name, prop)
            for key in ("anyOf", "oneOf", "allOf"):
                for member in schema.get(key) or []:
                    visit_object(member)
            if isinstance(schema.get("items"), dict):
                visit_object(schema["items"])
            if isinstance(schema.get("additionalProperties"), dict):
                visit_object(schema["additionalProperties"])

        for schema in self.schemas.values():
            visit_object(schema)
        for _, _, op in iter_operations(self.spec):
            for p in op.get("parameters", []):
                if p.get("in") == "query":
                    visit_field(p["name"], p.get("schema") or {})
        for field, sigs in sorted(usages.items()):
            if len(sigs) != 1:
                continue
            ident = type_ident(field)
            if ident in self.used or ident in RESERVED_TYPE_NAMES or not ident[0].isalpha():
                continue
            self.used.add(ident)
            self.shared_enums[(field, next(iter(sigs)))] = ident

    # --- type expressions: ("value",) ("object",) ("prim", t) ("named", n) ("vec", e) ("map", e) ("opt", e)

    def ty(self, schema: Any, hint: str, field: Optional[str] = None) -> tuple:
        if schema is True or not isinstance(schema, dict) or not schema:
            return ("value",)
        inner, nullable = self.split_null(schema)
        expr = self.ty_nonnull(inner, hint, field)
        if nullable and expr != ("value",):
            return ("opt", expr)
        return expr

    def ty_nonnull(self, schema: Any, hint: str, field: Optional[str]) -> tuple:
        if not isinstance(schema, dict) or not schema:
            return ("value",)
        if "$ref" in schema:
            name = schema["$ref"].rsplit("/", 1)[-1]
            if name not in self.names:
                raise SystemExit(f"unresolved $ref {schema['$ref']}")
            return ("named", self.names[name])
        all_of = schema.get("allOf")
        if isinstance(all_of, list) and all_of:
            if len(all_of) == 1 and not schema.get("properties"):
                return self.ty(all_of[0], hint, field)
            merged = self.merge_all_of(schema)
            return self.ty_nonnull(merged, hint, field)
        union = self.shape_union(schema)
        if union is not None:
            if len(union) == 1:
                return self.ty(union[0], hint, field)
            return ("named", self.define_union(schema, union, hint))
        sig = self.string_enum_signature(schema)
        if sig:
            return ("named", self.define_enum(schema, sig, hint, field))
        if "const" in schema:
            value = schema["const"]
            if isinstance(value, bool):
                return ("prim", "bool")
            if isinstance(value, int):
                return ("prim", "i64")
            if isinstance(value, float):
                return ("prim", "f64")
            return ("value",)
        if isinstance(schema.get("enum"), list):
            values = schema["enum"]
            if values and all(isinstance(v, bool) for v in values):
                return ("prim", "bool")
            if values and all(isinstance(v, int) and not isinstance(v, bool) for v in values):
                return ("prim", "i64")
            return ("value",)
        kind = schema.get("type")
        if isinstance(kind, list):
            members = [{**schema, "type": k} for k in kind]
            if len(members) == 1:
                return self.ty_nonnull(members[0], hint, field)
            return ("named", self.define_union(schema, members, hint))
        if kind == "string":
            return ("prim", "String")
        if kind == "integer":
            return ("prim", "i64")
        if kind == "number":
            return ("prim", "f64")
        if kind == "boolean":
            return ("prim", "bool")
        if kind == "null":
            return ("prim", "()")
        if kind == "array":
            items = schema.get("items")
            return ("vec", self.ty(items, hint + "Item", field) if isinstance(items, dict) else ("value",))
        if schema.get("properties"):
            return ("named", self.define_struct(schema, hint))
        if kind == "object" or "additionalProperties" in schema:
            extra = schema.get("additionalProperties")
            if isinstance(extra, dict) and extra:
                return ("map", self.ty(extra, hint + "Value"))
            return ("object",)
        return ("value",)

    def merge_all_of(self, schema: dict[str, Any]) -> dict[str, Any]:
        merged: dict[str, Any] = {"type": "object", "properties": {}, "required": []}
        for part in [schema, *schema.get("allOf", [])]:
            part = self.resolve(part)
            merged["properties"].update(part.get("properties") or {})
            for name in part.get("required") or []:
                if name not in merged["required"]:
                    merged["required"].append(name)
        if schema.get("description"):
            merged["description"] = schema["description"]
        return merged

    # --- definitions

    def define_enum(self, schema: dict[str, Any], sig: tuple, hint: str, field: Optional[str]) -> str:
        shared = self.shared_enums.get((field, sig)) if field else None
        if shared and shared in self.defs:
            return shared
        name = shared or self.unique(hint)
        self.add_def(name, enum_def(schema, sig))
        return name

    def define_union(self, schema: dict[str, Any], members: list[Any], hint: str, fixed: Optional[str] = None) -> str:
        name = fixed or self.unique(hint)
        self.add_def(name, {"kind": "pending"})
        variants: list[tuple[str, tuple]] = []
        seen: set[str] = set()
        exprs: list[tuple] = []
        for index, member in enumerate(members):
            label = self.variant_label(member)
            vname, n = label, 2
            while vname in seen:
                vname = f"{label}{n}"
                n += 1
            seen.add(vname)
            expr = self.ty(member, f"{name}{vname}")
            if expr in exprs:
                seen.discard(vname)
                continue
            exprs.append(expr)
            variants.append((vname, expr))
        # Catch-all JSON variants must come last, or they would swallow every value.
        variants.sort(key=lambda v: v[1] in (("value",), ("object",)))
        self.defs[name] = {"kind": "union", "doc": schema.get("description"), "variants": variants}
        return name

    def variant_label(self, member: Any) -> str:
        if not isinstance(member, dict) or not member:
            return "Json"
        if "$ref" in member:
            return self.names.get(member["$ref"].rsplit("/", 1)[-1], "Ref")
        inner, _ = self.split_null(member)
        if "const" in inner or "enum" in inner:
            return "Enum"
        kind = inner.get("type")
        if kind == "array":
            items = inner.get("items") if isinstance(inner.get("items"), dict) else {}
            return self.variant_label(items) + "List" if items else "List"
        if kind == "object" or inner.get("properties") or "additionalProperties" in inner:
            return "Object" if inner.get("properties") else "Map"
        return {"string": "String", "integer": "Integer", "number": "Number", "boolean": "Bool", "null": "Null"}.get(
            kind if isinstance(kind, str) else "", "Json"
        )

    def define_struct(self, schema: dict[str, Any], name: str, component: bool = False) -> str:
        if not component:
            name = self.unique(name)
        self.add_def(name, {"kind": "pending"})
        required = set(schema.get("required") or [])
        fields = []
        used: set[str] = set()
        for prop_name, prop in (schema.get("properties") or {}).items():
            ident = field_ident(prop_name)
            candidate, n = ident, 2
            while bare(candidate) in used:
                candidate = f"{bare(ident)}_{n}"
                n += 1
            used.add(bare(candidate))
            prop = prop if isinstance(prop, dict) else {}
            expr = self.ty(prop, f"{name}{pascal(prop_name)}", prop_name)
            resolved = prop
            if "allOf" in prop and len(prop["allOf"]) == 1:
                resolved = {**prop["allOf"][0], **{k: v for k, v in prop.items() if k != "allOf"}}
            fields.append(
                {
                    "name": prop_name,
                    "ident": candidate,
                    "expr": expr,
                    "required": prop_name in required,
                    "doc": resolved.get("description") or (self.split_null(prop)[0] or {}).get("description"),
                    "default": prop.get("default"),
                    "deprecated": bool(prop.get("deprecated")),
                }
            )
        self.defs[name] = {"kind": "struct", "doc": schema.get("description"), "fields": fields}
        return name

    def add_def(self, name: str, definition: dict[str, Any]) -> None:
        if name not in self.defs:
            self.order.append(name)
        self.defs[name] = definition

    def define_component(self, name: str, schema: dict[str, Any]) -> None:
        ident = self.names[name]
        inner, nullable = self.split_null(schema)
        if isinstance(inner, dict) and inner.get("properties") and not self.shape_union(inner) and "allOf" not in inner:
            self.define_struct(inner, ident, component=True)
            return
        sig = self.string_enum_signature(inner)
        if sig and not nullable:
            self.add_def(ident, enum_def(inner, sig))
            return
        union = self.shape_union(inner) if isinstance(inner, dict) else None
        if union is not None and len(union) > 1 and not nullable and not inner.get("properties"):
            self.define_union(inner, union, ident, fixed=ident)
            return
        expr = self.ty(schema, ident + "Inner")
        self.add_def(ident, {"kind": "alias", "doc": schema.get("description") if isinstance(schema, dict) else None, "expr": expr})

    # --- cycles: box direct (non-Vec/Map) self-references

    def compute_boxes(self) -> None:
        def direct_refs(expr: tuple) -> list[str]:
            if expr[0] == "named":
                return [expr[1]]
            if expr[0] == "opt":
                return direct_refs(expr[1])
            return []

        edges: dict[str, set[str]] = defaultdict(set)
        for name, d in self.defs.items():
            if d["kind"] == "struct":
                for f in d["fields"]:
                    edges[name].update(direct_refs(f["expr"]))
            elif d["kind"] == "union":
                for _, expr in d["variants"]:
                    edges[name].update(direct_refs(expr))
            elif d["kind"] == "alias":
                edges[name].update(direct_refs(d["expr"]))

        def reaches(start: str, target: str) -> bool:
            stack, seen = [start], set()
            while stack:
                node = stack.pop()
                if node == target:
                    return True
                if node in seen:
                    continue
                seen.add(node)
                stack.extend(edges.get(node, ()))
            return False

        def boxed(expr: tuple, owner: str) -> tuple:
            if expr[0] == "named" and reaches(expr[1], owner):
                return ("box", expr)
            if expr[0] == "opt":
                return ("opt", boxed(expr[1], owner))
            return expr

        for name, d in self.defs.items():
            if d["kind"] == "struct":
                for f in d["fields"]:
                    f["expr"] = boxed(f["expr"], name)
            elif d["kind"] == "union":
                d["variants"] = [(v, boxed(e, name)) for v, e in d["variants"]]

    # --- lenient response decoding

    def mark_lenient(self, roots: list[tuple]) -> None:
        """Mark every struct reachable from a response type as leniently decoded."""
        stack = list(roots)
        seen: set[str] = set()
        while stack:
            expr = stack.pop()
            if expr[0] in ("vec", "map", "opt", "box"):
                stack.append(expr[1])
                continue
            if expr[0] != "named" or expr[1] in seen:
                continue
            seen.add(expr[1])
            d = self.defs[expr[1]]
            if d["kind"] == "struct":
                d["lenient"] = True
                stack.extend(f["expr"] for f in d["fields"])
            elif d["kind"] == "union":
                stack.extend(e for _, e in d["variants"])
            elif d["kind"] == "alias":
                stack.append(d["expr"])

    def struct_of(self, expr: tuple) -> Optional[dict[str, Any]]:
        while expr[0] in ("box", "opt"):
            expr = expr[1]
        if expr[0] != "named":
            return None
        d = self.defs[expr[1]]
        if d["kind"] == "alias":
            return self.struct_of(d["expr"])
        return d if d["kind"] == "struct" else None

    def discriminators(self, expr: tuple) -> tuple[list[str], list[tuple[str, str]]]:
        """Required JSON keys and `const` string fields of a union variant that is a struct."""
        d = self.struct_of(expr)
        if d is None:
            return [], []
        required = [f["name"] for f in d["fields"] if f["required"]]
        consts = []
        for f in d["fields"]:
            inner = f["expr"]
            while inner[0] in ("box", "opt"):
                inner = inner[1]
            if inner[0] == "named" and self.defs[inner[1]]["kind"] == "enum" and self.defs[inner[1]].get("const") is not None:
                consts.append((f["name"], self.defs[inner[1]]["const"]))
        return required, consts


def enum_def(schema: dict[str, Any], sig: tuple) -> dict[str, Any]:
    kind, values = sig
    values = [values] if kind == "const" else list(dict.fromkeys(values))
    variants: list[tuple[str, str]] = []
    seen: set[str] = set()
    for value in values:
        vname = variant_name(value)
        candidate, n = vname, 2
        while candidate in seen:
            candidate = f"{vname}{n}"
            n += 1
        seen.add(candidate)
        variants.append((candidate, value))
    fallback = "Other"
    while fallback in seen:
        fallback = "Unknown" if fallback == "Other" else fallback + "Value"
    default = schema.get("default")
    return {
        "kind": "enum",
        "doc": schema.get("description"),
        "variants": variants,
        "fallback": fallback,
        "const": values[0] if kind == "const" else None,
        "default": default if default in values else values[0],
    }


def render_expr(expr: tuple, prefix: str = "") -> str:
    kind = expr[0]
    if kind == "value":
        return "serde_json::Value"
    if kind == "object":
        return "serde_json::Map<String, serde_json::Value>"
    if kind == "prim":
        return expr[1]
    if kind == "named":
        return prefix + expr[1]
    if kind == "vec":
        return f"Vec<{render_expr(expr[1], prefix)}>"
    if kind == "map":
        return f"std::collections::BTreeMap<String, {render_expr(expr[1], prefix)}>"
    if kind == "opt":
        return f"Option<{render_expr(expr[1], prefix)}>"
    if kind == "box":
        return f"Box<{render_expr(expr[1], prefix)}>"
    raise AssertionError(expr)


def default_note(value: Any) -> Optional[str]:
    if value is None:
        return None
    text = json.dumps(value, ensure_ascii=False, sort_keys=True)
    if len(text) > 120:
        return None
    return f"Server default: {code_span(text)}."


def render_types(gen: Gen) -> str:
    out = [
        HEADER,
        "//! Request and response types for every schema in the FreeAstroAPI OpenAPI document.",
        "//!",
        "//! Every type implements `Default`, so request values can be written with struct update",
        "//! syntax: `NatalChartRequest { year: 1990, month: 5, day: 15, ..Default::default() }`.",
        "//! Optional fields are `Option`s that are omitted from the JSON when `None`, letting the",
        "//! server apply its defaults. String enums carry an `Other(String)` variant for values added",
        "//! to the API after this SDK version was generated.",
        "//!",
        "//! Response types decode leniently: a missing field or a `null` becomes the field's default",
        "//! and unknown fields are ignored, so a response that drifts from the schema still decodes.\n",
        "use serde::{Deserialize, Serialize};\n",
    ]
    body: list[str] = []
    for name in sorted(gen.order):
        d = gen.defs[name]
        doc = render_doc(doc_lines(d.get("doc")))
        if d["kind"] == "struct":
            lenient = d.get("lenient", False)
            lines = [doc + "#[derive(Debug, Clone, PartialEq, Default, Serialize, Deserialize)]"]
            if lenient:
                lines.append("#[serde(default)]")
            lines.append(f"pub struct {name} {{")
            for f in d["fields"]:
                ty = render_expr(f["expr"])
                optional = not f["required"]
                if optional and not ty.startswith("Option<"):
                    ty = f"Option<{ty}>"
                fdoc = doc_lines(f["doc"], default_note(f["default"]), "Deprecated by the API." if f["deprecated"] else None)
                lines.append(render_doc(fdoc, "    ").rstrip("\n") if fdoc else None)
                attrs = []
                if bare(f["ident"]) != f["name"]:
                    attrs.append(f"rename = {rust_str(f['name'])}")
                if ty.startswith("Option<"):
                    if not lenient:
                        attrs.append("default")
                    if optional:
                        attrs.append('skip_serializing_if = "Option::is_none"')
                elif lenient and ty not in ("serde_json::Value", "()"):
                    attrs.append('deserialize_with = "crate::de::null_as_default"')
                if attrs:
                    lines.append(f"    #[serde({', '.join(attrs)})]")
                lines.append(f"    pub {f['ident']}: {ty},")
            lines.append("}\n")
            body.append("\n".join(line for line in lines if line is not None))
        elif d["kind"] == "enum":
            lines = [doc + "#[derive(Debug, Clone, PartialEq, Eq, Hash, Default, Serialize, Deserialize)]", f"pub enum {name} {{"]
            for vname, value in d["variants"]:
                if value == d["default"]:
                    lines.append("    #[default]")
                lines.append(f"    #[serde(rename = {rust_str(value)})]")
                lines.append(f"    {vname},")
            if d["fallback"]:
                lines.append("    /// A value this SDK version does not know about.")
                lines.append("    #[serde(untagged)]")
                lines.append(f"    {d['fallback']}(String),")
            lines.append("}\n")
            lines.append(f"impl {name} {{")
            lines.append("    /// The wire value of this variant.")
            lines.append("    pub fn as_str(&self) -> &str {")
            lines.append("        match self {")
            for vname, value in d["variants"]:
                lines.append(f"            Self::{vname} => {rust_str(value)},")
            if d["fallback"]:
                lines.append(f"            Self::{d['fallback']}(value) => value,")
            lines.append("        }")
            lines.append("    }")
            lines.append("}\n")
            lines.append(f"impl std::fmt::Display for {name} {{")
            lines.append("    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {")
            lines.append("        f.write_str(self.as_str())")
            lines.append("    }")
            lines.append("}\n")
            body.append("\n".join(lines))
        elif d["kind"] == "union":
            lines = [
                doc + "#[derive(Debug, Clone, PartialEq, Serialize)]",
                "#[serde(untagged)]",
                "#[allow(clippy::large_enum_variant)]",
                f"pub enum {name} {{",
            ]
            for vname, expr in d["variants"]:
                lines.append(f"    {vname}({render_expr(expr)}),")
            lines.append("}\n")
            lines.append(f"impl<'de> Deserialize<'de> for {name} {{")
            lines.append("    fn deserialize<D: serde::Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {")
            lines.append(f"        crate::de::union(deserializer, {rust_str(name)}, &[")
            for vname, expr in d["variants"]:
                required, consts = gen.discriminators(expr)
                req = ", ".join(rust_str(r) for r in required)
                con = ", ".join(f"({rust_str(k)}, {rust_str(v)})" for k, v in consts)
                lines.append(
                    f"            crate::de::Variant {{ required: &[{req}], consts: &[{con}], "
                    f"decode: |value| serde_json::from_value(value).map(Self::{vname}) }},"
                )
            lines.append("        ])")
            lines.append("    }")
            lines.append("}\n")
            first = d["variants"][0][0]
            lines.append(f"impl Default for {name} {{")
            lines.append("    fn default() -> Self {")
            lines.append(f"        Self::{first}(Default::default())")
            lines.append("    }")
            lines.append("}\n")
            body.append("\n".join(lines))
        elif d["kind"] == "alias":
            body.append(doc + f"pub type {name} = {render_expr(d['expr'])};\n")
        else:
            raise AssertionError(f"unfinished definition {name}")
    return "\n".join(out) + "\n" + "\n".join(body)


