def rustfmt(text: str) -> str:
    """Format with the toolchain's rustfmt so `cargo fmt --check` and `--check` agree."""
    result = subprocess.run(
        ["rustfmt", "--edition", "2024", "--emit", "stdout", "--config-path", str(ROOT)],
        input=text,
        capture_output=True,
        text=True,
        encoding="utf-8",
    )
    if result.returncode != 0:
        sys.stderr.write(text[:2000] if len(text) < 2000 else "")
        raise SystemExit(f"rustfmt failed:\n{result.stderr[:4000]}")
    return result.stdout


def main(argv: Optional[list[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--spec", default=str(ROOT / "spec" / "freeastro.json"))
    parser.add_argument("--out-dir", default=str(ROOT / "src" / "generated"))
    parser.add_argument("--tests-file", default=str(ROOT / "tests" / "operations.rs"))
    parser.add_argument("--contract-file", default=str(ROOT / "tests" / "contract.rs"))
    parser.add_argument("--check", action="store_true", help="fail if the generated files are out of date")
    args = parser.parse_args(argv)

    spec = json.loads(Path(args.spec).read_text(encoding="utf-8"))
    spec_sync.validate(spec)
    gen = Gen(spec)
    ops = collect_operations(spec)
    assign_names(ops)
    gen.collect_enum_fields()
    prepare(gen, ops)
    out_dir = Path(args.out_dir)
    files = {
        out_dir / "mod.rs": render_mod(),
        out_dir / "types.rs": render_types(gen),
        out_dir / "params.rs": render_params(ops),
        out_dir / "resources.rs": render_resources(ops),
        out_dir / "operations.rs": render_operations(ops),
        Path(args.tests_file): render_tests(spec, ops),
        Path(args.contract_file): render_contract_tests(spec, ops),
    }
    files = {path: rustfmt(text) for path, text in files.items()}
    if args.check:
        stale = [str(p) for p, text in files.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
        if stale:
            print(f"out of date: {', '.join(stale)}; run python3 scripts/generate.py && cargo fmt", file=sys.stderr)
            return 1
        print(f"checked {len(ops)} operations, {len(gen.defs)} types")
        return 0
    out_dir.mkdir(parents=True, exist_ok=True)
    Path(args.tests_file).parent.mkdir(parents=True, exist_ok=True)
    for path, text in files.items():
        with open(path, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
    print(f"generated {len(ops)} operations, {len(gen.schemas)} schemas, {len(gen.defs)} Rust types")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
