def iter_operations(spec: dict[str, Any]):
    for path, item in (spec.get("paths") or {}).items():
        if not isinstance(item, dict):
            continue
        shared = item.get("parameters", [])
        for method in HTTP_METHODS:
            op = item.get(method)
            if isinstance(op, dict):
                params = list(op.get("parameters", []))
                names = {(p.get("in"), p.get("name")) for p in params}
                params += [p for p in shared if (p.get("in"), p.get("name")) not in names]
                yield path, method, {**op, "parameters": params}


def is_json(content_type: str) -> bool:
    return spec_sync.is_json(content_type)


def is_text(content_type: str) -> bool:
    base = content_type.split(";")[0].strip().lower()
    return base.startswith("text/") or base.endswith("+xml") or base in ("application/xml", "image/svg+xml")


def collect_operations(spec: dict[str, Any]) -> list[dict[str, Any]]:
    ops: list[dict[str, Any]] = []
    for path, method, op in iter_operations(spec):
        if path == "/natal":
            version, segments = 1, ["natal", "simple"]
        else:
            match = re.match(r"^/api/v(\d+)/(.*)$", path)
            if not match:
                raise SystemExit(f"unexpected public path {path}")
            version, segments = int(match[1]), [s for s in match[2].split("/") if s]
        params = op.get("parameters", [])
        body = (op.get("requestBody") or {}).get("content", {})
        body_ct = next((ct for ct in sorted(body) if is_json(ct)), None)
        codes = sorted(c for c in (op.get("responses") or {}) if str(c).startswith("2"))
        ok = ((op.get("responses") or {}).get(codes[0]) or {}).get("content") or {} if codes else {}
        json_ct = next((ct for ct in sorted(ok) if is_json(ct)), None)
        other = [ct for ct in ok if not is_json(ct)]
        if json_ct and other:
            kind = "content"
        elif json_ct or not ok:
            kind = "json"
        elif all(is_text(ct) for ct in other):
            kind = "text"
        else:
            kind = "binary"
        ops.append(
            {
                "id": op["operationId"],
                "method": method.upper(),
                "path": path,
                "op": op,
                "version": version,
                "resource": snake(segments[0]),
                "rest": segments[1:],
                "path_params": [p for p in params if p.get("in") == "path"],
                "query_params": [p for p in params if p.get("in") == "query"],
                "body": None if body_ct is None else (body[body_ct] or {}).get("schema") or {},
                "body_required": bool((op.get("requestBody") or {}).get("required")),
                "response": (ok.get(json_ct) or {}).get("schema") if json_ct else None,
                "kind": kind,
                "content_types": list(ok),
                "status": int(codes[0]) if codes else 200,
                "side_effects": op["operationId"] in SIDE_EFFECT_OPERATIONS,
            }
        )
    seen: dict[str, str] = {}
    for o in ops:
        if o["id"] in seen:
            raise SystemExit(f"duplicate operationId {o['id']}")
        seen[o["id"]] = o["path"]
    return ops


def assign_names(ops: list[dict[str, Any]]) -> None:
    """Same rule as the TypeScript and Python SDKs: latest version gets the plain name."""
    direct = set()
    for o in ops:
        literal_rest = [s for s in o["rest"] if not is_param(s)]
        if len(literal_rest) == 1:
            direct.add((o["resource"], literal_rest[0]))
    for o in ops:
        literal_rest = [s for s in o["rest"] if not is_param(s)]
        sub = None
        name_parts = literal_rest
        if len(literal_rest) >= 2 and not is_param(o["rest"][0]) and (o["resource"], o["rest"][0]) not in direct:
            sub = snake(o["rest"][0])
            name_parts = literal_rest[1:]
        o["sub"] = sub
        o["base_name"] = snake("-".join(name_parts)) if name_parts else EMPTY_NAME.get(o["id"], "get")
    groups: dict[tuple, list[dict[str, Any]]] = defaultdict(list)
    for o in ops:
        groups[(o["resource"], o["sub"], o["base_name"])].append(o)
    for group in groups.values():
        latest = max(o["version"] for o in group)
        if len({o["version"] for o in group}) != len(group):
            raise SystemExit(f"name clash: {[o['id'] for o in group]}")
        for o in group:
            o["name"] = o["base_name"] if o["version"] == latest else f"{o['base_name']}_v{o['version']}"
    members: dict[str, str] = {}
    for o in ops:
        o["accessor"] = [o["resource"], *([o["sub"]] if o["sub"] else []), o["name"]]
        top = f"{o['resource']}.{o['sub'] or o['name']}"
        kind = "sub" if o["sub"] else "method"
        if members.setdefault(top, kind) != kind:
            raise SystemExit(f"member clash on {top}")
    reserved_client = {"builder", "new", "from_env", "with_options", "request", "base_url", "clone", "fmt"}
    for o in ops:
        if o["resource"] in reserved_client:
            raise SystemExit(f"resource {o['resource']} clashes with a Client method")


def method_ident(name: str) -> str:
    if name in NON_RAW_KEYWORDS:
        return name + "_"
    return "r#" + name if name in RUST_KEYWORDS else name


def resource_type(resource: str, sub: Optional[str]) -> str:
    return pascal(resource) + (pascal(sub) if sub else "")


def params_type(o: dict[str, Any]) -> str:
    return "".join(pascal(p) for p in o["accessor"]) + "Params"


def prepare(gen: Gen, ops: list[dict[str, Any]]) -> None:
    for name, schema in gen.schemas.items():
        gen.define_component(name, schema if isinstance(schema, dict) else {})
    params_gen_names: set[str] = set()
    for o in ops:
        base = "".join(pascal(p) for p in o["accessor"])
        o["body_expr"] = gen.ty(o["body"], base + "Request") if o["body"] is not None else None
        if o["kind"] in ("json", "content"):
            expr = gen.ty(o["response"], base + "Response") if o["response"] else ("value",)
            o["response_expr"] = ("value",) if expr == ("object",) else expr
        else:
            o["response_expr"] = None
        o["params_fields"] = []
        for p in o["query_params"]:
            schema = p.get("schema") or {}
            o["params_fields"].append(
                {
                    "name": p["name"],
                    "ident": field_ident(p["name"]),
                    "expr": gen.ty(schema, base + pascal(p["name"]), p["name"]),
                    "required": bool(p.get("required")),
                    "doc": p.get("description") or schema.get("description"),
                    "default": schema.get("default"),
                    "deprecated": bool(p.get("deprecated")),
                }
            )
        if o["params_fields"]:
            name = params_type(o)
            if name in params_gen_names:
                raise SystemExit(f"params type clash {name}")
            params_gen_names.add(name)
    gen.compute_boxes()
    gen.mark_lenient([o["response_expr"] for o in ops if o["response_expr"] is not None])


def render_params(ops: list[dict[str, Any]]) -> str:
    out = [
        HEADER,
        "//! Query parameters for operations that take them, one struct per operation.\n",
        "#![allow(unused_imports)]\n",
        "use serde::{Deserialize, Serialize};\n",
        "use crate::types::*;\n",
    ]
    for o in ops:
        if not o["params_fields"]:
            continue
        lines = [
            f"/// Query parameters for {code_span(o['method'] + ' ' + o['path'])}.",
            "#[derive(Debug, Clone, PartialEq, Default, Serialize, Deserialize)]",
            f"pub struct {params_type(o)} {{",
        ]
        for f in o["params_fields"]:
            ty = render_expr(f["expr"])
            optional = not f["required"]
            if optional and not ty.startswith("Option<"):
                ty = f"Option<{ty}>"
            fdoc = doc_lines(f["doc"], default_note(f["default"]), "Deprecated by the API." if f["deprecated"] else None)
            if fdoc:
                lines.append(render_doc(fdoc, "    ").rstrip("\n"))
            attrs = []
            if bare(f["ident"]) != f["name"]:
                attrs.append(f"rename = {rust_str(f['name'])}")
            if ty.startswith("Option<"):
                attrs.append("default")
                if optional:
                    attrs.append('skip_serializing_if = "Option::is_none"')
            if attrs:
                lines.append(f"    #[serde({', '.join(attrs)})]")
            lines.append(f"    pub {f['ident']}: {ty},")
        lines.append("}\n")
        out.append("\n".join(lines))
    return "\n".join(out)


def return_type(o: dict[str, Any]) -> str:
    if o["kind"] == "json":
        return render_expr(o["response_expr"], "types::")
    if o["kind"] == "content":
        return f"Content<{render_expr(o['response_expr'], 'types::')}>"
    if o["kind"] == "text":
        return "String"
    return "Binary"


def accept_header(o: dict[str, Any]) -> Optional[str]:
    if o["kind"] == "json":
        return None
    types = list(o["content_types"])
    if not any(is_json(t) for t in types):
        types.append("application/json")
    return ", ".join(types)


def params_optional(o: dict[str, Any]) -> bool:
    """Operations whose query parameters are all optional take `Option<&Params>`."""
    return not any(f["required"] for f in o["params_fields"])


def render_method(o: dict[str, Any]) -> str:
    args = ["&self"]
    path_expr = rust_str(o["path"])
    path_args = []
    for p in o["path_params"]:
        ident = field_ident(p["name"])
        args.append(f"{ident}: impl std::fmt::Display")
        path_args.append(ident)
    if path_args:
        fmt = re.sub(r"\{([^}]+)\}", "{}", o["path"])
        path_expr = f"format!({rust_str(fmt)}, " + ", ".join(f"encode_path({a})" for a in path_args) + ")"
    if o["body_expr"] is not None:
        body_ty = render_expr(o["body_expr"], "types::")
        args.append(f"body: &{body_ty}")
    if o["params_fields"]:
        if params_optional(o):
            args.append(f"params: Option<&params::{params_type(o)}>")
        else:
            args.append(f"params: &params::{params_type(o)}")
    summary = o["op"].get("summary") or o["id"]
    description = (o["op"].get("description") or "").strip()
    lines = doc_lines(summary, None if description == summary else description)
    lines += ["", f"{code_span(o['method'] + ' ' + o['path'])} (operation {code_span(o['id'])})."]
    if o["kind"] == "binary":
        lines += ["", "Returns the raw body; use [`Binary::text`] for SVG output."]
    if o["side_effects"]:
        lines += [
            "",
            "Has side effects: retried on 429, but on server errors, timeouts and network failures only",
            "with an idempotency key or [`RequestOptions::retry_side_effects`](crate::RequestOptions::retry_side_effects).",
        ]
    if o["op"].get("deprecated"):
        lines += ["", "**Deprecated** by the API."]
    out = render_doc(lines, "    ")
    if o["op"].get("deprecated"):
        out += '    #[deprecated(note = "this operation is deprecated by the API")]\n'
    out += f"    pub async fn {method_ident(o['name'])}({', '.join(args)}) -> Result<{return_type(o)}> {{\n"
    chain = f"RequestSpec::operation({rust_str(o['id'])}, Method::{o['method']}, {path_expr})"
    if o["body_expr"] is not None:
        chain += ".json(body)?"
    if o["params_fields"] and not params_optional(o):
        chain += ".query(params)?"
    accept = accept_header(o)
    if accept:
        chain += f".accept({rust_str(accept)})"
    if o["params_fields"] and params_optional(o):
        out += f"        let mut request = {chain};\n"
        out += "        if let Some(params) = params {\n            request = request.query(params)?;\n        }\n"
    else:
        out += f"        let request = {chain};\n"
    call = {"json": "send_json", "content": "send_content", "text": "send_text", "binary": "send_binary"}[o["kind"]]
    out += f"        self.client.{call}(request).await\n    }}\n"
    return out


def render_resources(ops: list[dict[str, Any]]) -> str:
    resources: dict[str, dict[str, Any]] = {}
    for o in ops:
        r = resources.setdefault(o["resource"], {"methods": [], "subs": defaultdict(list)})
        if o["sub"]:
            r["subs"][o["sub"]].append(o)
        else:
            r["methods"].append(o)
    out = [
        HEADER,
        "//! Resource handles for every public operation, grouped by API path.",
        "//!",
        "//! `client.western().natal().insights(&body)` calls `POST /api/v1/western/natal/insights`.",
        "//! When an operation exists in several API versions the plain name calls the latest one and",
        "//! older ones carry a suffix: `client.vedic().chart(..)` is v2, `chart_v1(..)` is v1.\n",
        "#![allow(unused_imports)]\n",
        "use reqwest::Method;\n",
        "use crate::client::{encode_path, RequestSpec};",
        "use crate::{params, types, Binary, Client, Content, Result};\n",
    ]
    accessors = []
    for resource in sorted(resources):
        r = resources[resource]
        top = resource_type(resource, None)
        accessors.append((resource, top))
        for sub in sorted(r["subs"]):
            name = resource_type(resource, sub)
            out.append(
                f"/// Operations under {code_span('/' + resource.replace('_', '-') + '/' + sub.replace('_', '-'))}.\n"
                f"#[derive(Debug, Clone, Copy)]\npub struct {name}<'a> {{\n    client: &'a Client,\n}}\n"
            )
            out.append(f"impl<'a> {name}<'a> {{")
            out.append("\n".join(render_method(o) for o in r["subs"][sub]))
            out.append("}\n")
        out.append(
            f"/// Operations under {code_span('/' + resource.replace('_', '-'))}.\n"
            f"#[derive(Debug, Clone, Copy)]\npub struct {top}<'a> {{\n    client: &'a Client,\n}}\n"
        )
        out.append(f"impl<'a> {top}<'a> {{")
        members = []
        for sub in sorted(r["subs"]):
            members.append(
                f"    /// Operations under {code_span('/' + resource.replace('_', '-') + '/' + sub.replace('_', '-'))}.\n"
                f"    pub fn {method_ident(sub)}(&self) -> {resource_type(resource, sub)}<'a> {{\n"
                f"        {resource_type(resource, sub)} {{ client: self.client }}\n    }}\n"
            )
        members += [render_method(o) for o in r["methods"]]
        out.append("\n".join(members))
        out.append("}\n")
    out.append("impl Client {")
    out.append(
        "\n".join(
            f"    /// Operations under {code_span('/' + res.replace('_', '-'))}.\n"
            f"    pub fn {method_ident(res)}(&self) -> {top}<'_> {{\n        {top} {{ client: self }}\n    }}\n"
            for res, top in accessors
        )
    )
    out.append("}\n")
    return "\n".join(out)


def render_operations(ops: list[dict[str, Any]]) -> str:
    rows = []
    for o in ops:
        accessor = ", ".join(rust_str(a) for a in o["accessor"])
        rows.append(
            "    OperationInfo {\n"
            f"        operation_id: {rust_str(o['id'])},\n"
            f"        method: {rust_str(o['method'])},\n"
            f"        path: {rust_str(o['path'])},\n"
            f"        accessor: &[{accessor}],\n"
            f"        deprecated: {'true' if o['op'].get('deprecated') else 'false'},\n"
            "    },"
        )
    return (
        HEADER
        + "\nuse crate::OperationInfo;\n\n"
        + "/// Every public operation and the client method that calls it, in spec order.\n"
        + "pub static OPERATIONS: &[OperationInfo] = &[\n"
        + "\n".join(rows)
        + "\n];\n\n"
        + "/// Operations with side effects (paid report jobs, AI generation, chat, stored timelines).\n"
        + "///\n"
        + "/// They are retried on 429 like every operation, but on 408/5xx responses, timeouts and\n"
        + "/// network errors only when the request carries an idempotency key or opts in with\n"
        + "/// [`RequestOptions::retry_side_effects`](crate::RequestOptions::retry_side_effects).\n"
        + "pub static SIDE_EFFECT_OPERATIONS: &[&str] = &[\n"
        + "".join(f"    {rust_str(i)},\n" for i in SIDE_EFFECT_OPERATIONS)
        + "];\n"
    )


def render_mod() -> str:
    return (
        HEADER
        + "\npub(crate) mod operations;\npub mod params;\npub mod resources;\npub mod types;\n"
    )


# ---------------------------------------------------------------- operation tests


def sample_response(spec: dict[str, Any], o: dict[str, Any]) -> tuple[str, bytes, str]:
    """(content type, body, kind) the mock server returns for an operation."""
    if o["kind"] in ("json", "content"):
        value = spec_sync.sample(spec, o["response"]) if o["response"] else {}
        if value is None:
            value = {}
        ct = next((ct for ct in o["content_types"] if is_json(ct)), "application/json")
        return ct, json.dumps(value, ensure_ascii=False, sort_keys=True).encode(), "json"
    ct = o["content_types"][0]
    if is_text(ct):
        return ct, b"<svg xmlns=\"http://www.w3.org/2000/svg\"/>" if "svg" in ct else b"# FreeAstroAPI\n", "text"
    return ct, b"\x89PNG\r\n\x1a\n" if "png" in ct else b"%PDF-1.7\n", "binary"


def render_tests(spec: dict[str, Any], ops: list[dict[str, Any]]) -> str:
    out = [
        HEADER.replace("Do not edit by hand.", "Do not edit by hand.\n//\n// One test per operation: the sample request deserialises into the SDK's request type, the\n// method sends it to the right method/path and the sample response decodes into the return type."),
        "#![allow(deprecated, clippy::all)]\n",
        "mod common;\n",
        "use common::{json_response, loose_json, raw_response, setup};",
        "use freeastroapi::{params, types};",
        "use wiremock::matchers::{method, path, query_param};",
        "use wiremock::Mock;\n",
    ]
    for o in ops:
        sample = spec_sync.samples({"paths": {o["path"]: {o["method"].lower(): o["op"]}}, "components": spec.get("components", {})})[o["id"]]
        lines = [f"#[tokio::test]\nasync fn {o['id'].lower()}() {{", "    let (server, client) = setup().await;"]
        path = o["path"]
        args = []
        for p in o["path_params"]:
            value = sample["path_params"].get(p["name"])
            value = "x" if value is None else str(value).lower() if isinstance(value, bool) else str(value)
            path = path.replace("{" + p["name"] + "}", value)
            args.append(rust_str(value))
        mock = f"    Mock::given(method({rust_str(o['method'])}))\n        .and(path({rust_str(path)}))"
        if o["body_expr"] is not None:
            body = json.dumps(sample.get("body"), ensure_ascii=False, sort_keys=True)
            mock += f"\n        .and(loose_json({raw_str(body)}))"
        query = sample.get("query") or {}
        for name in sorted(query):
            value = query[name]
            if isinstance(value, list):
                continue
            text = str(value).lower() if isinstance(value, bool) else str(value)
            mock += f"\n        .and(query_param({rust_str(name)}, {rust_str(text)}))"
        ct, payload, kind = sample_response(spec, o)
        if kind == "json":
            mock += f"\n        .respond_with(json_response({o['status']}, {raw_str(payload.decode())}))"
        else:
            literal = "b\"" + "".join(chr(b) if 32 <= b < 127 and chr(b) not in '"\\' else f"\\x{b:02x}" for b in payload) + "\""
            mock += f"\n        .respond_with(raw_response({o['status']}, {rust_str(ct)}, {literal}))"
        mock += "\n        .expect(1)\n        .mount(&server)\n        .await;"
        lines.append(mock)
        if o["body_expr"] is not None:
            body_ty = render_expr(o["body_expr"], "types::")
            lines.append(
                f"    let body: {body_ty} =\n        serde_json::from_str({raw_str(json.dumps(sample.get('body'), ensure_ascii=False, sort_keys=True))}).expect(\"sample request decodes\");"
            )
            args.append("&body")
        if o["params_fields"]:
            lines.append(
                f"    let params: params::{params_type(o)} =\n        serde_json::from_str({raw_str(json.dumps(query, ensure_ascii=False, sort_keys=True))}).expect(\"sample params decode\");"
            )
            args.append("Some(&params)" if params_optional(o) else "&params")
        call = "client." + ".".join(
            [method_ident(a) + "()" for a in o["accessor"][:-1]] + [f"{method_ident(o['accessor'][-1])}({', '.join(args)})"]
        )
        lines.append(f"    let result = {call}.await.expect(\"call succeeds\");")
        if kind == "text":
            lines.append(f"    assert!(!result.is_empty());")
        elif kind == "binary" and o["kind"] == "binary":
            lines.append(f"    assert_eq!(result.content_type.as_deref(), Some({rust_str(ct)}));")
        else:
            lines.append("    let _ = result;")
        lines.append("}\n")
        out.append("\n".join(lines))
    return "\n".join(out)


def render_contract_tests(spec: dict[str, Any], ops: list[dict[str, Any]]) -> str:
    out = [
        HEADER.replace(
            "Do not edit by hand.",
            "Do not edit by hand.\n//\n"
            "// Contract tests: every method against a Stoplight Prism mock of the spec, with the minimal\n"
            "// valid requests from `scripts/spec_sync.py samples`. Ignored by default; run with\n"
            "//     python3 scripts/with_prism.py -- cargo test --test contract -- --ignored",
        ),
        "#![allow(deprecated, clippy::all)]\n",
        "mod common;\n",
        "#[allow(unused_imports)]",
        "use common::contract;",
        "#[allow(unused_imports)]",
        "use freeastroapi::{params, types};\n",
    ]
    for o in ops:
        sample = spec_sync.samples({"paths": {o["path"]: {o["method"].lower(): o["op"]}}, "components": spec.get("components", {})})[o["id"]]
        lines = [f'#[tokio::test]\n#[ignore = "needs PRISM_URL: scripts/with_prism.py"]\nasync fn {o["id"].lower()}() {{']
        args = []
        clones = []
        for p in o["path_params"]:
            value = sample["path_params"].get(p["name"])
            args.append(rust_str("x" if value is None else str(value).lower() if isinstance(value, bool) else str(value)))
        if o["body_expr"] is not None:
            body_ty = render_expr(o["body_expr"], "types::")
            lines.append(
                f"    let body: {body_ty} = serde_json::from_str({raw_str(json.dumps(sample.get('body'), ensure_ascii=False, sort_keys=True))}).unwrap();"
            )
            clones.append("body")
            args.append("&body")
        if o["params_fields"]:
            query = sample.get("query") or {}
            lines.append(
                f"    let params: params::{params_type(o)} = serde_json::from_str({raw_str(json.dumps(query, ensure_ascii=False, sort_keys=True))}).unwrap();"
            )
            clones.append("params")
            args.append("Some(&params)" if params_optional(o) else "&params")
        call = "client." + ".".join(
            [method_ident(a) + "()" for a in o["accessor"][:-1]] + [f"{method_ident(o['accessor'][-1])}({', '.join(args)})"]
        )
        rebind = "".join(f"let {c} = {c}.clone(); " for c in clones)
        lines.append(f"    contract({rust_str(o['id'])}, |client| {{ {rebind}async move {{ {call}.await }} }}).await;")
        lines.append("}\n")
        out.append("\n".join(lines))
    return "\n".join(out)


